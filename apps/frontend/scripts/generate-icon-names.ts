/**
 * Writes the Lucide icon names `packages/content` accepts for every `icono`
 * of a content repository: the names `DynamicIcon` can draw with the
 * installed `lucide-react`, aliases included. Run by `bun run icons:catalog`
 * after upgrading `lucide-react`; commit the output. Needs no network.
 */

import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { iconNames } from "lucide-react/dynamic"

const FRONTEND_DIR = fileURLToPath(new URL("..", import.meta.url))
const OUTPUT_FILE = join(
  FRONTEND_DIR,
  "../../packages/content/src/lucide-icons.generated.ts"
)

async function installedLucideVersion() {
  const manifest: { version: string } = JSON.parse(
    await readFile(
      join(FRONTEND_DIR, "node_modules/lucide-react/package.json"),
      "utf8"
    )
  )
  return manifest.version
}

const version = await installedLucideVersion()
const names = [...iconNames].sort()
const lines = names.map((name) => `  "${name}",`).join("\n")
await writeFile(
  OUTPUT_FILE,
  `// Generated by apps/frontend/scripts/generate-icon-names.ts — do not edit.
// Lucide ${version}: every name lucide-react's DynamicIcon draws.

export const LUCIDE_ICON_NAMES = [
${lines}
] as const
`
)
console.log(`Wrote ${names.length} icon names (Lucide ${version}).`)
